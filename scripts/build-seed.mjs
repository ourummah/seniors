// Builds supabase/seed.sql from the gathered benefit files in data/benefits/*.json.
// Usage: node scripts/build-seed.mjs   (prints a summary and any problems found)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'

const DIR = new URL('../data/benefits/', import.meta.url)
const CATEGORIES = new Set(['Payments', 'Bills', 'Transport', 'Health', 'Home and Rates', 'Discounts'])
const LEVELS = new Set(['Federal', 'State', 'Council', 'Private'])
const STATES = new Set(['ALL', 'NSW', 'VIC', 'QLD', 'WA', 'SA', 'TAS', 'ACT', 'NT'])
const CARDS = new Set(['PCC', 'HCC', 'CSHC', 'DVA_GOLD', 'DVA_WHITE', 'SENIORS_CARD', 'NONE'])
const TAGS = new Set(['homeowner', 'renter', 'electricity_account', 'gas_account', 'water_account', 'car_owner', 'carer', 'lives_alone', 'life_support', 'medical_condition', 'mobility_need', 'hearing_need', 'rural', 'age_pension', 'aged_60', 'aged_65', 'aged_67', 'aged_70', 'veteran', 'low_income', 'hardship'])

// Benefits that need two cards held together (the plain "cards" list means any one card).
const CARD_SETS = {
  'WA-002': [['SENIORS_CARD', 'PCC'], ['SENIORS_CARD', 'CSHC']],
  'WA-009': [['PCC'], ['DVA_GOLD'], ['SENIORS_CARD', 'CSHC']],
  'WA-011': [['PCC'], ['DVA_GOLD'], ['SENIORS_CARD', 'CSHC']],
  'WA-014': [['PCC'], ['DVA_GOLD'], ['SENIORS_CARD', 'CSHC']],
  'WA-028': [['PCC'], ['SENIORS_CARD', 'CSHC']],
}

// Hide a benefit from members who already have it.
const EXCLUDES = {
  'FED-001': ['age_pension'], 'FED-007': ['PCC'], 'FED-008': ['CSHC', 'PCC'],
  ...Object.fromEntries(['ACT-016', 'NSW-012', 'NSW-013', 'QLD-012', 'QLD-014', 'SA-012', 'TAS-009', 'VIC-027', 'WA-020', 'NT-012'].map((id) => [id, ['SENIORS_CARD']])),
}
// Large means-tested income payments: listed, but left out of the headline "up to $X a year".
const NOT_IN_TOTAL = new Set(['FED-001', 'FED-005', 'FED-010', 'FED-011', 'FED-031', 'FED-033'])

const q = (v) => (v === null || v === undefined || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`

const problems = []
const rows = []
const seen = new Set()
const summary = []
for (const file of readdirSync(DIR).filter((f) => f.endsWith('.json')).sort()) {
  const data = JSON.parse(readFileSync(new URL(file, DIR), 'utf8'))
  summary.push(`${data.jurisdiction}: ${data.benefits.length} records`)
  for (const b of data.benefits) {
    const where = `${file} ${b.id}`
    if (seen.has(b.id)) { problems.push(`${where}: duplicate id, skipped`); continue }
    seen.add(b.id)
    for (const k of ['name', 'provider', 'source_url']) if (!b[k]) problems.push(`${where}: missing ${k}`)
    if (!/^https?:\/\//.test(b.source_url ?? '')) { problems.push(`${where}: bad source_url, skipped`); continue }
    if (!CATEGORIES.has(b.category)) problems.push(`${where}: unknown category ${b.category}, using Discounts`)
    if (!LEVELS.has(b.level)) problems.push(`${where}: unknown level ${b.level}, using State`)
    if (!STATES.has(b.state)) { problems.push(`${where}: unknown state ${b.state}, skipped`); continue }
    const cards = (b.cards ?? []).filter((c) => CARDS.has(c) || (problems.push(`${where}: dropped card ${c}`), false))
    const requires = (b.requires ?? []).filter((t) => TAGS.has(t) || (problems.push(`${where}: dropped tag ${t}`), false))
    const value = typeof b.max_annual_value === 'number' && b.max_annual_value > 0 ? b.max_annual_value : null
    rows.push(`(${[
      q(b.id), q(b.name), q(b.provider), q(LEVELS.has(b.level) ? b.level : 'State'), q(b.state),
      q(CATEGORIES.has(b.category) ? b.category : 'Discounts'), q(b.summary ?? ''), arr(cards.length ? cards : ['NONE']),
      CARD_SETS[b.id] ? `'${JSON.stringify(CARD_SETS[b.id])}'::jsonb` : 'null', arr(requires), arr(EXCLUDES[b.id] ?? []), NOT_IN_TOTAL.has(b.id) ? 'false' : 'true',
      q(b.eligibility_text ?? ''), q(b.value_text ?? ''), value ?? 'null', q(b.value_period), q(b.how_to_claim ?? ''),
      q(b.phone), q(b.source_url), q(b.notes),
    ].join(', ')})`)
  }
}

const sql = `-- Generated by scripts/build-seed.mjs on ${new Date().toISOString().slice(0, 10)}. All amounts unverified until checked in the admin area.
insert into public.benefits (id, name, provider, level, state, category, summary, cards, card_sets, requires, excludes, counts_in_total, eligibility_text, value_text, max_annual_value, value_period, how_to_claim, phone, source_url, notes)
values
${rows.join(',\n')}
on conflict (id) do nothing;
`
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(summary.join('\n'))
console.log(`Total: ${rows.length} records written to supabase/seed.sql`)
if (problems.length) console.log(`\n${problems.length} problems:\n` + problems.join('\n'))
